"""Create 6 test invitation images from text descriptions."""
import os
from PIL import Image, ImageDraw, ImageFont

FONT_TAMIL = "C:/Windows/Fonts/Nirmala.ttf"

def create_invitation_image(text_lines, output_path, title=None, bg_color=(255,255,255), font_size=28, line_spacing=6, margin=80, title_font_size=48):
    """Render text lines into an invitation-style image."""
    font = ImageFont.truetype(FONT_TAMIL, font_size)
    title_font = ImageFont.truetype(FONT_TAMIL, title_font_size) if title else font
    width = 1600
    height = margin * 2 + line_spacing * len(text_lines) * (font_size // 2) + (title_font_size if title else 0)
    img = Image.new("RGB", (width, height), bg_color)
    draw = ImageDraw.Draw(img)
    y = margin
    if title:
        draw.text((width//2, y), title, fill=(0,0,0), font=title_font, anchor="mm")
        y += title_font_size + line_spacing * 2
    for line in text_lines:
        if line.strip():
            draw.text((width//2, y), line.strip(), fill=(0,0,0), font=font, anchor="mm")
            y += font_size + line_spacing
        else:
            y += (font_size + line_spacing) // 2
    img.save(output_path, "PNG")
    print(f"Created: {output_path}")
    return img

